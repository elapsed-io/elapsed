/**
 * Security headers and the Content Security Policy (plan, Custom CSS safety >
 * Required defences 2; Infrastructure and security review > Security
 * requirements). One definition feeds both the Cloudflare `_headers` file in
 * the build output and the local preview server, so what is tested is what
 * deploys.
 */

export type CspDirectives = Readonly<Record<string, readonly string[]>>;

/**
 * The plan's policy, directive for directive, plus Trusted Types.
 *
 * - frame-src: the plan allows only the widget origin. That origin is a second
 *   domain registered before Release 4, so until then no frame is allowed.
 * - require-trusted-types-for / trusted-types: browsers that support Trusted
 *   Types refuse every string passed to an HTML or script sink (innerHTML,
 *   script src, ...). No policy may be created, so the page cannot opt back in.
 *   Browsers without support ignore both directives.
 */
export const CSP_DIRECTIVES: CspDirectives = {
  'default-src': ["'none'"],
  'script-src': ["'self'"],
  'style-src': ["'self'"],
  'img-src': ["'self'", 'data:', 'blob:'],
  'font-src': ["'self'"],
  'connect-src': ["'self'"],
  'frame-src': ["'none'"],
  'base-uri': ["'none'"],
  'form-action': ["'self'"],
  'frame-ancestors': ["'none'"],
  'require-trusted-types-for': ["'script'"],
  'trusted-types': ["'none'"],
};

export function renderCsp(directives: CspDirectives = CSP_DIRECTIVES): string {
  return Object.entries(directives)
    .map(([name, sources]) => [name, ...sources].join(' '))
    .join('; ');
}

export type HeaderSet = Readonly<Record<string, string>>;

export interface HeaderRule {
  /** A Cloudflare `_headers` path pattern; `*` matches any run of characters. */
  readonly path: string;
  readonly headers: HeaderSet;
}

export const SECURITY_HEADERS: HeaderSet = {
  'Content-Security-Policy': renderCsp(),
  // Two years, all subdomains, and consent to preload-list submission.
  'Strict-Transport-Security': 'max-age=63072000; includeSubDomains; preload',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'no-referrer',
  'Cross-Origin-Opener-Policy': 'same-origin',
  // Off until a release needs them.
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
};

export const HEADER_RULES: readonly HeaderRule[] = [
  { path: '/*', headers: SECURITY_HEADERS },
  // Vite writes hashed file names here, so they never change in place.
  { path: '/assets/*', headers: { 'Cache-Control': 'public, max-age=31536000, immutable' } },
];

/** Renders Cloudflare's `_headers` format (static assets on Pages and Workers). */
export function renderHeadersFile(rules: readonly HeaderRule[] = HEADER_RULES): string {
  const blocks = rules.map(({ path, headers }) =>
    [path, ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)].join('\n'),
  );
  return `# Generated by packages/web/build/headers.ts. Do not edit.\n${blocks.join('\n\n')}\n`;
}

function matches(pattern: string, path: string): boolean {
  const escaped = pattern.split('*').map((part) => part.replace(/[.+?^${}()|[\]\\]/g, '\\$&'));
  return new RegExp(`^${escaped.join('.*')}$`).test(path);
}

/** The headers Cloudflare would send for a request path, in rule order. */
export function headersForPath(path: string, rules: readonly HeaderRule[] = HEADER_RULES): HeaderSet {
  const result: Record<string, string> = {};
  for (const rule of rules) {
    if (matches(rule.path, path)) Object.assign(result, rule.headers);
  }
  return result;
}
